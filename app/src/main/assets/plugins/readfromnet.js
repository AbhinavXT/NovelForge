/** Stable merge sort (Kotlin's sortWith is stable; Rhino's Array.sort is not guaranteed to be). */
function stableSort(arr, cmp) {
  if (arr.length < 2) return arr;
  var mid = arr.length >> 1;
  var a = stableSort(arr.slice(0, mid), cmp), b = stableSort(arr.slice(mid), cmp);
  var out = [], i = 0, j = 0;
  while (i < a.length && j < b.length) out.push(cmp(b[j], a[i]) < 0 ? b[j++] : a[i++]);
  return out.concat(a.slice(i), b.slice(j));
}

/** String.toInt(): throws on anything that isn't an integer. */
function toInt(s) {
  if (!/^[+-]?\d+$/.test(s)) throw new Error("NumberFormatException: For input string: \"" + s + "\"");
  return parseInt(s, 10);
}

function afterSpace(s) {
  var i = s.indexOf(" ");
  return i >= 0 ? s.substring(i + 1) : s;
}

function compareStrings(a, b) {
  return a < b ? -1 : a > b ? 1 : 0;
}

function posterOf(h) {
  var img = h.selectFirst("div > a.highslide > img");
  return fixUrlNull(img ? img.attr("src") : null);
}

