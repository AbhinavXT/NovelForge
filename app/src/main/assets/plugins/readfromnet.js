  browseNovels: function (page, f) {
    var doc = qnGet(MAIN_URL + "/" + f.tag + "/page/" + page + "/", { headers: BASE_HEADERS }).document();
    var out = [];
    doc.select("div.box_in").forEach(function (h) {
      var h2 = h.selectFirst("h2");
      if (!h2) return;
      var a = h.selectFirst(" div > h2.title > a ");
      if (!a) return;
      out.push(qnItem(h2.text(), fixUrl(attr(a, "href")), posterOf(h)));
    });
    return out;
  },

  popularNovels: function (page) {
    return qnPopular(page);
  },

  searchNovels: function (query) {
    var doc = qnGet(MAIN_URL + "/build_in_search/?q=" + query, { headers: BASE_HEADERS }).document();
    var out = [];
    doc.select("div > article > div.box_in[id='search result']").forEach(function (h) {
      var b = h.selectFirst(" div > h2.title > a > b");
      if (!b) return;
      var a = h.selectFirst(" div > h2.title > a ");
      var cUrl = fixUrlNull(a ? a.attr("href") : null) || "";
      out.push(qnItem(b.text(), fixUrl(cUrl), posterOf(h)));
    });
    return out;
  },

  parseNovel: function (url) {
    var doc = qnGet(url, { headers: BASE_HEADERS }).document();
    var h2 = doc.selectFirst(" h2 ");
    if (!h2) return null;
    var name = h2.text();
    if (name.indexOf(", page") >= 0) name = name.substring(0, name.indexOf(", page"));
    if (name.indexOf("#") >= 0) name = name.substring(0, name.indexOf("#"));

    var links = doc.select("div.splitnewsnavigation2.ignore-select > center > div > a");
    var slash = url.lastIndexOf("/");
    var data = [{
      name: "page 1",
      url: fixUrl(slash >= 0 ? url.substring(0, slash) + "/page,1," + url.substring(slash + 1) : url + "/page,1," + url)
    }];
    // Like the original, this throws (no details) when there are no page links.
    for (var c = 0; c <= Math.floor(links.length / 2); c++) {
      var href = links[c].attr("href") || "";
      if (href.indexOf("category") < 0) data.push({ name: "page " + links[c].text(), url: fixUrl(href) });
    }
    data = stableSort(data, function (first, second) {
      var a = afterSpace(first.name), b = afterSpace(second.name);
      return a !== b ? toInt(a) - toInt(b) : compareStrings(first.name, second.name);
    });
    var seen = {};
    data = data.filter(function (d) {
      if (seen[d.url]) return false;
      seen[d.url] = true;
      return true;
    });

    var authorEl = doc.selectFirst("#dle-speedbar > div > div > ul > li:nth-child(3) > a > span");
    var img = doc.selectFirst("div.box_in > center > div > a > img");
    return qnNovel(name, data, {
      author: authorEl ? authorEl.text() : null,
      posterUrl: fixUrlNull(img ? img.attr("src") : null)
    });
  },

  parseChapter: function (url) {
    var doc = qnGet(url, { headers: BASE_HEADERS }).document();
    doc.select("div.splitnewsnavigation").forEach(function (n) { n.remove(); });
    doc.select("div.splitnewsnavigation2").forEach(function (n) { n.remove(); });
    var text = doc.selectFirst("#textToRead");
    return text ? text.html() : null;
  }
